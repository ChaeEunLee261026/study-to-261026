/* 출생년도와 주민등록번호 뒷자리의 첫 번째 숫자를 이용하여 
나이와 성별을 판별하는 프로그램을 작성
사용자 입력은 받지 않으며, 아래와 같이 변수를 미리 선언하여 사용

let year = 2000; // 출생년도
let num = 3; // 주민등록번호 뒷자리 첫 번째 숫자

요구사항)
기준년도는 2026

나이는 2026 - 출생년도 + 1로 계산
ex) 2000년생 → 27살 / 1996년생 → 31살

출생년도에 따라 주민등록번호 뒷자리 첫 번째 숫자를 구분
2000년 이전 출생: 남자 1, 여자 2
2000년 이후 출생(2000년 포함): 남자 3, 여자 4
출생년도와 주민등록번호 숫자의 조합이 올바르지 않으면 "잘못된 입력입니다."를 출력
출생년도가 1900년 미만이거나 2026년을 초과하는 경우에도 잘못된 입력으로 처리

작성 조건)
if, else if, else 조건문을 사용
비교 연산자와 논리 연산자(&&, ||)를 활용
결과는 console.log()로 출력
year, num 변수의 값을 변경하면서 여러 조건을 테스트 */



let year = 2000; // 출생년도
let num = 3; // 주민등록번호 뒷자리 첫 번째 숫자

let age = 2026 - year + 1;

// 출생년도가 잘못된 경우
if (year < 1900 || year > 2026) {
    console.log("잘못된 입력입니다.");
}

// 2000년 이전 출생자
else if (year < 2000 && num == 1) {
    console.log(age + "살 / 남자");
}
else if (year < 2000 && num == 2) {
    console.log(age + "살 / 여자");
}

// 2000년 이후 출생자 (2000년 포함)
else if (year >= 2000 && num == 3) {
    console.log(age + "살 / 남자");
}
else if (year >= 2000 && num == 4) {
    console.log(age + "살 / 여자");
}

// 나머지는 모두 잘못된 입력
else {
    console.log("잘못된 입력입니다.");
}

/* &&(and_그리고) : 두 조건이 모두 맞아야 실행 
   ||(or_~이거나)  : 둘중 하나만 맞아도 실행
   if : 만약 ~라면
   else if : 그렇지 않고, 만약 ~라면
   else : 위 조건이 모두 아니라면 */ 

