# 문제2)
# n = [-32, 5, 2, -10, 55, 7, 9, 0]
# - 홀수 번째 인덱스(1, 3, 5 ...)의 요소만 출력하세요.
# - 마지막 3개 요소를 출력하세요.
# - 리스트를 거꾸로 뒤집어서 출력하세요.
n = [-32, 5, 2, -10, 55, 7, 9, 0]
print(n[1::2])
print(n[-3:])
